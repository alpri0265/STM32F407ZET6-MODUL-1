void ili9341_fill_screen(uint16_t color)
{
    ili9341_fill_rect(0, 0, TFT_WIDTH, TFT_HEIGHT, color);
}

void ili9341_fill_rect(int16_t x, int16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > TFT_WIDTH)  w = TFT_WIDTH - x;
    if (y + h > TFT_HEIGHT) h = TFT_HEIGHT - y;
    if (w <= 0 || h <= 0) return;

    set_addr_window(x, y, x + w - 1, y + h - 1);
    HAL_GPIO_WritePin(TFT_DC_PORT, TFT_DC_PIN, GPIO_PIN_SET);
    HAL_GPIO_WritePin(TFT_CS_PORT, TFT_CS_PIN, GPIO_PIN_RESET);

    uint32_t n = (uint32_t)w * h;
    for (uint32_t i = 0; i < n; i++) {
        spiwrite(color >> 8);
        spiwrite(color & 0xFF);
    }
    HAL_GPIO_WritePin(TFT_CS_PORT, TFT_CS_PIN, GPIO_PIN_SET);
}

void ili9341_draw_pixel(int16_t x, int16_t y, uint16_t color)
{
    if (x < 0 || x >= TFT_WIDTH || y < 0 || y >= TFT_HEIGHT) return;
    set_addr_window(x, y, x, y);
    write_data16(color);
}

void ili9341_draw_char(int16_t x, int16_t y, char c, uint16_t fg, uint16_t bg)
{
    const uint8_t *glyph;
    const int scale = 2;  /* 5x7 -> 10x14 для читабельності на 3.2" */
    uint8_t gw = 5, gh = 7;

    if ((uint8_t)c == 0xFF) {
        static const uint8_t deg[] = {0x0E, 0x11, 0x11, 0x0E, 0x00};
        glyph = deg;
    } else if (c >= 0x20 && c <= 0x7E) {
        glyph = &font5x7[(c - 0x20) * 5];
    } else {
        glyph = &font5x7[0];
    }

    for (int col = 0; col < gw; col++) {
        uint8_t line = glyph[col];
        for (int row = 0; row < gh; row++) {
            uint16_t color = (line & (1 << row)) ? fg : bg;
            ili9341_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
        }
    }
}

void ili9341_draw_string(int16_t x, int16_t y, const char *str, uint16_t fg, uint16_t bg)
{
    while (*str) {
        ili9341_draw_char(x, y, *str, fg, bg);
        x += FONT_W;
        str++;
    }
}
